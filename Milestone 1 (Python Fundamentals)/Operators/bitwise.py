# Bitwise AND
print("5 & 3 =", 5 & 3)     # 0101 & 0011 = 0001 → 1

# Bitwise OR
print("5 | 3 =", 5 | 3)     # 0101 | 0011 = 0111 → 7

# Bitwise XOR
print("5 ^ 3 =", 5 ^ 3)     # 0101 ^ 0011 = 0110 → 6

# Bitwise NOT
print("~5 =", ~5)           # ~0101 = -(0101 + 1) = -6 (Two's complement)

# Bitwise Left Shift
print("5 << 1 =", 5 << 1)   # 0101 << 1 = 1010 → 10

# Bitwise Right Shift
print("5 >> 1 =", 5 >> 1)   # 0101 >> 1 = 0010 → 2
